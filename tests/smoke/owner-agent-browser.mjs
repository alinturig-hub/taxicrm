import assert from "node:assert/strict";
import { randomUUID, createHash } from "node:crypto";
import { createRequire } from "node:module";
import { readFile } from "node:fs/promises";
import { join } from "node:path";
import { encode } from "next-auth/jwt";
import { prisma } from "../../src/lib/prisma.ts";
const { chromium } = createRequire(import.meta.url)("playwright");
assert.equal(process.env.DATABASE_URL, "postgresql://analytics_test@127.0.0.1:55438/analytics_synthetic");
assert.equal(process.env.TAXICRM_SYNTHETIC_TESTS, "1");
const origin = "http://127.0.0.1:3001", prefix = "owner-agent-ui-" + randomUUID(), users = [];
let browser;
const sleep = ms => new Promise(resolve => setTimeout(resolve, ms));
async function token(user) { return encode({ secret: process.env.NEXTAUTH_SECRET, token: { id: user.id, sub: user.id, email: user.email, name: user.name, role: user.role, mustChangePassword: false }, maxAge: 3600 }); }
try {
  for (const role of ["ADMIN", "MANAGER", "OPERATOR"]) users.push(await prisma.user.create({ data: { email: `${prefix}-${role.toLowerCase()}@example.test`, name: "Synthetic Agent " + role, role, passwordHash: "synthetic-unusable" } }));
  await prisma.booking.create({ data: { provider: prefix, externalId: "1", status: "COMPLETED", price: 17.1, cost: 19, pickupDueTime: new Date(Date.now() - 600000), bookedAtTime: new Date(Date.now() - 900000), paymentType: "Cash", rawPayload: { synthetic: true, loyalty: 1.9 } } });
  const before = await prisma.booking.findMany({ where: { provider: prefix } });
  const admin = await token(users[0]), manager = await token(users[1]), operator = await token(users[2]);
  const request = (method, body, auth = admin, originHeader = origin) => fetch(origin + "/api/dashboard/ai/owner-agent", { method, headers: { "content-type": "application/json", origin: originHeader, cookie: "next-auth.session-token=" + auth }, ...(body ? { body: JSON.stringify(body) } : {}) });
  assert.equal((await fetch(origin + "/api/dashboard/ai/owner-agent")).status, 401);
  assert.equal((await request("GET", null, operator)).status, 200);
  assert.equal((await request("POST", { question: "margin" }, operator)).status, 403);
  assert.equal((await request("POST", { question: "margin" }, admin, "https://other.example")).status, 403);
  const tenantResponse = await request("POST", { question: "margin", tenantId: "other" });
  assert.equal(tenantResponse.status, 400, JSON.stringify(await tenantResponse.json()));
  assert.equal((await request("PUT", { confirm: false, expectedRevision: 0 })).status, 400);
  assert.equal((await request("POST", { question: "x".repeat(5000) })).status, 413);
  assert.equal((await request("POST", { question: "margin", preset: "custom", from: "2026-01-01", to: "2026-03-01" })).status, 400);
  assert.equal((await request("PUT", { confirm: true, expectedRevision: 0, preferences: { priority: "BALANCED", style: "BRIEF" } }, manager)).status, 403);
  const restricted = await (await request("POST", { question: "delete all bookings" })).json();
  assert.equal(restricted.restricted, true);
  const report = await (await request("POST", { question: "Explain company margin", preset: "last-6-hours", payment: "ALL" })).json();
  assert.equal(report.answer.metrics[2].value, -1.9);
  assert.equal(report.safeguards.modelUsed, false);
  assert.equal(report.safeguards.writeActionsEnabled, false);
  assert.equal((await request("POST", { question: "margin" })).status, 429);
  browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ viewport: { width: 1440, height: 1050 } });
  await context.addCookies([{ name: "next-auth.session-token", value: admin, url: origin }]);
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.route("**/*", route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
  await page.goto(origin + "/dashboard/ai/owner-agent");
  await page.getByRole("heading", { name: "Synthetic Company Agent" }).waitFor();
  await page.getByLabel("Business priority").selectOption("REDUCE_NO_FARE");
  await page.getByLabel("Report detail").selectOption("DETAILED");
  await page.getByRole("button", { name: "Review preference change" }).click();
  await page.getByText("Proposed: Review no-fare outcomes", { exact: false }).waitFor();
  const initial = await (await request("GET")).json();
  await page.getByRole("button", { name: "Confirm company preference" }).click();
  await page.getByText(`Confirmed company preference · revision ${initial.memory.revision + 1}.`, { exact: false }).waitFor();
  await page.reload();
  await page.getByRole("heading", { name: "Synthetic Company Agent" }).waitFor();
  assert.equal(await page.getByLabel("Business priority").inputValue(), "REDUCE_NO_FARE");
  await page.getByLabel("Agent pickup period").selectOption("last-6-hours");
  await sleep(3100);
  await page.getByRole("button", { name: "Explain company margin", exact: true }).click();
  await page.getByRole("heading", { name: "Company money and driver money", exact: true }).waitFor();
  await page.getByText("-£1.90", { exact: true }).waitFor();
  await page.screenshot({ path: "/workspace/taxicrm-local/owner-agent-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/workspace/taxicrm-local/owner-agent-mobile.png", fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "Mobile layout overflows");
  assert.deepEqual(errors, []);
  assert.deepEqual(await prisma.booking.findMany({ where: { provider: prefix } }), before);
  const file = join(process.env.TAXICRM_AGENT_MEMORY_DIR, createHash("sha256").update("synthetic-agent-company").digest("hex") + ".json");
  const memory = JSON.parse(await readFile(file, "utf8"));
  assert.equal(memory.history.at(-1).actor, users[0].id);
  assert.doesNotMatch(JSON.stringify(memory), /Explain company margin|delete all bookings|password|rawPayload/);
  console.log("Owner agent browser passed: RBAC, CSRF, tenant-input refusal, explicit preference confirmation/reload, signed money, no database writes, quota, mobile and no external calls.");
} finally {
  await browser?.close();
  await prisma.booking.deleteMany({ where: { provider: prefix } });
  await prisma.user.deleteMany({ where: { id: { in: users.map(u => u.id) } } });
  await prisma.$disconnect();
}
