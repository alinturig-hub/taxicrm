import assert from "node:assert/strict";
import { randomUUID } from "node:crypto";
import { createRequire } from "node:module";
import { encode } from "next-auth/jwt";
import { prisma } from "../../src/lib/prisma.ts";
import { buildCustomerProfile } from "../../src/lib/customers/customer-profiler.ts";
const { chromium } = createRequire(import.meta.url)("playwright");
assert.equal(process.env.DATABASE_URL, "postgresql://analytics_test@127.0.0.1:55438/analytics_synthetic");
assert.equal(process.env.TAXICRM_SYNTHETIC_TESTS, "1");
const origin = "http://127.0.0.1:3001", prefix = "contribution-ui-" + randomUUID();
const users = []; let browser, contact;
const token = user => encode({ secret: process.env.NEXTAUTH_SECRET, token: { id: user.id, sub: user.id, email: user.email, name: user.name, role: user.role, mustChangePassword: false }, maxAge: 3600 });
const delay = () => new Promise(resolve => setTimeout(resolve, 3100));
try {
  for (const role of ["ADMIN", "OPERATOR"]) users.push(await prisma.user.create({ data: { role, email: `${prefix}-${role.toLowerCase()}@example.test`, name: "Synthetic contribution " + role, passwordHash: "synthetic-unusable" } }));
  contact = await prisma.normalCustomer.create({ data: { normalizedTelephone: prefix, displayName: "Synthetic contribution contact", telephoneNumber: "SYNTHETIC" } });
  const make = (externalId, extra = {}) => prisma.booking.create({ data: { provider: prefix, externalId, status: "COMPLETED", price: 17.1, cost: 19, pickupDueTime: new Date("2059-10-26T12:00:00Z"), normalCustomerId: contact.id, paymentType: "Cash", rawPayload: { synthetic: true }, ...extra } });
  await make("cash"); await make("account", { accountId: "SYNTHETIC-ACCOUNT", accountName: "Synthetic account display", paymentType: "Account", price: 50, cost: 45 }); await make("unknown", { normalCustomerId: null, price: 0, cost: 0 }); await make("card", { paymentType: "Card", price: null, cost: 2 }); await make("cancelled", { status: "CANCELLED", price: 999, cost: 1 });
  const before = await prisma.booking.findMany({ where: { provider: prefix }, orderBy: { id: "asc" } });
  const admin = await token(users[0]), operator = await token(users[1]);
  const endpoint = origin + "/api/dashboard/analytics/contribution";
  const headers = { cookie: "next-auth.session-token=" + admin };
  assert.equal((await fetch(endpoint)).status, 401);
  assert.equal((await fetch(endpoint, { headers: { cookie: "next-auth.session-token=" + operator } })).status, 403);
  assert.equal((await fetch(endpoint + "?preset=custom&from=2059-02-30&to=2059-03-01", { headers })).status, 400);
  assert.equal((await fetch(endpoint + "?preset=custom&from=2059-01-01&to=2059-03-01", { headers })).status, 400);
  browser = await chromium.launch({ executablePath: "/usr/bin/chromium", headless: true, args: ["--no-sandbox"] });
  const context = await browser.newContext({ locale: "en-GB", viewport: { width: 1440, height: 1050 } });
  await context.addCookies([{ name: "next-auth.session-token", value: admin, url: origin }]);
  const page = await context.newPage(), errors = [];
  page.on("pageerror", e => errors.push(e.message));
  await page.route("**/*", route => route.request().url().startsWith(origin) ? route.continue() : route.abort());
  await page.goto(origin + "/dashboard/analytics/contribution");
  await page.getByRole("heading", { name: "Customer & account contribution", exact: true }).waitFor();
  assert.equal(await page.getByRole("heading", { name: "Evidence coverage" }).count(), 0, "No unsolicited query on initial render");
  await page.getByLabel("Contribution period").selectOption("custom");
  await page.getByLabel("From", { exact: true }).fill("2059-10-26");
  await page.getByLabel("To inclusive", { exact: true }).fill("2059-10-26");
  async function run(expected = 200) { const response = page.waitForResponse(r => r.url().startsWith(endpoint) && r.request().method() === "GET"); await page.getByRole("button", { name: "Run contribution review" }).click(); const r = await response; assert.equal(r.status(), expected); return r.json(); }
  const all = await run();
  assert.equal(all.coverage.completed, 4); assert.equal(all.coverage.unattributed, 1);
  await page.getByRole("heading", { name: "Evidence coverage" }).waitFor();
  await page.getByText("Synthetic account display", { exact: true }).first().waitFor();
  await page.getByText("Pareto unavailable: Missing financial data.", { exact: true }).first().waitFor();
  await page.screenshot({ path: "/workspace/taxicrm-local/contribution-desktop.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.screenshot({ path: "/workspace/taxicrm-local/contribution-mobile.png", fullPage: true });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "Contribution page overflows on mobile");
  await delay(); await page.getByLabel("Contribution payment").selectOption("CASH");
  const cash = await run(); assert.equal(cash.coverage.completed, 2);
  assert.equal(cash.groups.find(g => g.kind === "CUSTOMER" && g.metric === "marginPence").total, -190);
  await page.getByText("1 negative contributors · -£1.90. Signed amounts retained.", { exact: true }).waitFor();
  await run(429); await page.locator("p[role=alert]").waitFor();
  assert.equal(await page.getByRole("heading", { name: "Evidence coverage" }).count(), 0, "Failed run must not retain stale results");
  await delay(); await page.getByLabel("Contribution payment").selectOption("ACCOUNT"); const account = await run(); assert.equal(account.coverage.completed, 1);
  assert.equal(account.groups.find(g => g.kind === "ACCOUNT" && g.metric === "grossPence").total, 5000);
  await delay(); await page.getByLabel("From", { exact: true }).fill("2059-10-27"); await page.getByLabel("To inclusive", { exact: true }).fill("2059-10-27");
  const empty = await run(); assert.equal(empty.coverage.completed, 0); await page.getByText("Pareto unavailable: No positive denominator.", { exact: true }).first().waitFor();
  await page.getByLabel("From", { exact: true }).fill("2059-01-01"); await run(400); await page.locator("p[role=alert]").waitFor();
  assert.equal(await page.getByRole("heading", { name: "Evidence coverage" }).count(), 0);
  // Profile UI is rendered with the real pure calculator output; mock its existing GET route
  // to prevent weather/snapshot side effects. Contribution API above uses real local SQL.
  const profileBookings = before.map(b => ({ ...b, locations: [] }));
  const profile = buildCustomerProfile(profileBookings, new Date("2059-10-27T12:00:00Z"));
  assert.equal(profile.overview.totalSpent, 67.1);
  await page.route(`**/api/dashboard/customers/${contact.id}/profile`, route => route.fulfill({ json: { success: true, customer: { id: contact.id, name: contact.displayName, telephoneNumber: "SYNTHETIC" }, profile } }));
  await page.goto(origin + "/dashboard/customers");
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.getByRole("button", { name: "Normal Customers", exact: true }).click();
  await page.getByRole("button", { name: contact.displayName, exact: true }).click();
  await page.getByRole("heading", { name: "Observed completed-trip activity", exact: true }).waitFor();
  await page.screenshot({ path: "/workspace/taxicrm-local/contribution-profile-mobile.png", fullPage: false });
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), "Profile layout overflows on mobile");
  await page.keyboard.press("Escape");
  await page.getByRole("heading", { name: "Observed completed-trip activity", exact: true }).waitFor({ state: "hidden" });
  const limited = await browser.newContext(); await limited.addCookies([{ name: "next-auth.session-token", value: operator, url: origin }]);
  const blocked = await limited.newPage(); await blocked.goto(origin + "/dashboard/analytics/contribution"); assert.ok(!blocked.url().includes("/analytics/contribution"));
  await limited.close();
  assert.deepEqual(errors, []);
  assert.deepEqual(await prisma.booking.findMany({ where: { provider: prefix }, orderBy: { id: "asc" } }), before);
  console.log("PASS: desktop/mobile contribution, custom/payment filters, signed/missing money, empty/invalid/rate-limited states, profile observations (synthetic route fixture), API/page permissions, no source mutations.");
} finally {
  await browser?.close();
  await prisma.booking.deleteMany({ where: { provider: prefix } });
  if (contact) await prisma.normalCustomer.delete({ where: { id: contact.id } });
  await prisma.user.deleteMany({ where: { id: { in: users.map(u => u.id) } } });
  await prisma.$disconnect();
}
